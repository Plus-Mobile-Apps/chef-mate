package com.plusmobileapps.chefmate.grocery.data

data class ParsedIngredient(val name: String, val quantity: String?, val category: GroceryCategory)

object IngredientParser {

    // The leading number may be a plain integer/decimal run or a unicode vulgar fraction
    // (bare, like "½", or attached to a whole number, like "1½") — recipes commonly use these
    // glyphs instead of "1/2".
    private val QUANTITY_PATTERN =
        Regex(
            """^\s*((?:\d+|[½⅓⅔¼¾⅕⅖⅗⅘⅙⅚⅛⅜⅝⅞])[\d/.  ½⅓⅔¼¾⅕⅖⅗⅘⅙⅚⅛⅜⅝⅞-]*\s*(?:cups?|tbsp|tsp|tablespoons?|teaspoons?|oz|ounces?|lbs?|pounds?|g|grams?|kg|kilograms?|ml|milliliters?|liters?|l|quarts?|qt|gallons?|gal|pints?|pt|cans?|bottles?|packages?|pkgs?|bags?|bunche?s?|heads?|cloves?|stalks?|slices?|pieces?|sticks?|sprigs?|ears?|large|medium|small|whole|pinch(?:es)?|dash(?:es)?|handful(?:s)?)?)\s+(.+)$""",
            RegexOption.IGNORE_CASE,
        )

    fun parse(raw: String): ParsedIngredient {
        val trimmed = raw.trim()
        if (trimmed.isBlank()) {
            return ParsedIngredient(
                name = trimmed,
                quantity = null,
                category = GroceryCategory.OTHER,
            )
        }

        val match = QUANTITY_PATTERN.matchEntire(trimmed)
        val name: String
        val quantity: String?
        if (match != null) {
            quantity = match.groupValues[1].trim()
            name = match.groupValues[2].trim()
        } else {
            quantity = null
            name = trimmed
        }

        val category = categorize(name)
        return ParsedIngredient(name = name, quantity = quantity, category = category)
    }

    fun suggestedNamesFor(
        query: String,
        maxSuggestions: Int = DEFAULT_MAX_SUGGESTIONS,
    ): List<String> {
        val normalizedQuery = parse(query).name.trim().lowercase()
        if (normalizedQuery.isBlank()) return emptyList()

        return CATEGORY_MAP.asSequence()
            .map { it.first }
            .distinct()
            .filter { it.lowercase().startsWith(normalizedQuery) }
            .take(maxSuggestions)
            .map { it.toSuggestionDisplayName() }
            .toList()
    }

    /**
     * Every built-in ingredient name, as display strings, sorted case-insensitively. Used by the
     * grocery autocomplete settings screen to show the read-only "defaults" section beneath the
     * user's own entries.
     */
    fun allSuggestionNames(): List<String> =
        CATEGORY_MAP.asSequence()
            .map { it.first }
            .distinct()
            .map { it.toSuggestionDisplayName() }
            .distinct()
            .sortedBy { it.lowercase() }
            .toList()

    private val PARENTHETICAL_PATTERN = Regex("""\s*\([^)]*\)""")

    private fun String.toSuggestionDisplayName(): String =
        SUGGESTION_DISPLAY_NAMES[this]
            ?: replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }

    private fun categorize(name: String): GroceryCategory {
        val lower = name.lowercase().replace(PARENTHETICAL_PATTERN, "").trim()
        for ((keyword, category) in CATEGORY_MAP) {
            if (lower.contains(keyword)) {
                return category
            }
        }
        return GroceryCategory.OTHER
    }

