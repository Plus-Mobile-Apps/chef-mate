package com.plusmobileapps.chefmate.recipe.core.root

import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import com.arkivanov.decompose.router.stack.ChildStack
import com.arkivanov.decompose.value.Value
import com.arkivanov.essenty.backhandler.BackHandlerOwner
import com.plusmobileapps.chefmate.BackClickBloc
import com.plusmobileapps.chefmate.BlocContext
import com.plusmobileapps.chefmate.Consumer
import com.plusmobileapps.chefmate.recipe.core.addmeal.MealPlannerRootBloc
import com.plusmobileapps.chefmate.recipe.core.detail.RecipeDetailBloc
import com.plusmobileapps.chefmate.recipe.core.edit.EditRecipeBloc
import com.plusmobileapps.chefmate.recipe.data.ExtractedRecipeData
import com.plusmobileapps.chefmate.ui.ComposeScreen
import kotlinx.serialization.Serializable

interface RecipeRootBloc : BackHandlerOwner, BackClickBloc, ComposeScreen {
    val routerState: Value<ChildStack<*, Child>>

    @Composable
    override fun Content(modifier: Modifier) {
        RecipeRootScreen(recipeRootBloc = this, modifier = modifier)
    }

    sealed class Child {

        abstract val bloc: ComposeScreen

        data class Detail(override val bloc: RecipeDetailBloc) : Child()

        data class Edit(override val bloc: EditRecipeBloc) : Child()
    }

    sealed class Output {
        data object Finished : Output()

        data class OpenUrl(val url: String) : Output()

        data object OpenGroceryList : Output()

        data class OpenMealPlanner(val props: MealPlannerRootBloc.Props) : Output()

        data class OpenCookMode(val recipeId: Long) : Output()

        data class OpenAiChat(val recipeId: Long) : Output()
    }

    @Serializable
    sealed class Props {
        /**
         * The detail of the recipe with [recipeId]. [initialTitle] is the title the opener already
         * knows (e.g. from the recipe list), shown while the full recipe loads so the header isn't
         * blank.
         *
         * Equality is by [recipeId] alone: [initialTitle] is only a loading hint, so opening the
         * same recipe with or without one must still match (and reuse) the same stack entry.
         */
        @Serializable
        data class Detail(val recipeId: Long, val initialTitle: String? = null) : Props() {
            override fun equals(other: Any?): Boolean =
                other is Detail && other.recipeId == recipeId

            override fun hashCode(): Int = recipeId.hashCode()
        }

        @Serializable data object Create : Props()

        @Serializable
        data class CreateFromExtracted(
            val extracted: ExtractedRecipeData,
            /**
             * When true, the recipe was generated by AI chat and is auto-tagged with the AI
             * category.
             */
            val fromAi: Boolean = false,
            /**
             * When true, the Edit Recipe screen pulls the photo that was picked for extraction from
             * [com.plusmobileapps.chefmate.recipe.data.PendingRecipePhotoStore] and pre-fills it as
             * the pending recipe image.
             */
            val consumePendingPhoto: Boolean = false,
        ) : Props()
    }

    fun interface Factory {
        fun create(context: BlocContext, props: Props, output: Consumer<Output>): RecipeRootBloc
    }
}
